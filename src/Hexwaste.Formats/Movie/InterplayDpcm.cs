/// <summary>
/// The Interplay MVE DPCM audio codec (P132), ported from fallout2-ce src/movie_lib.cc
/// _MVE_sndDecompM16 (:1330) / _MVE_sndDecompS16 (:1349) + the delta table word_51EBE0.
/// Each compressed audio frame is self-contained: it opens with the raw int16 initial
/// predictor per channel, then one delta byte per sample-channel — a running 16-bit
