    /// <summary>Decode one self-contained MVE audio frame to PCM16. <paramref name="stereo"/>
    /// selects the two-predictor interleaved path. Returns little-endian PCM16 bytes.</summary>
    public static byte[] DecodeFrame(ReadOnlySpan<byte> frame, bool stereo) =>
        stereo ? DecodeStereo(frame) : DecodeMono(frame);

    private static byte[] DecodeMono(ReadOnlySpan<byte> frame)
    {
        if (frame.Length < 2)
            return [];
        int count = 1 + (frame.Length - 2);
        var pcm = new byte[count * 2];
        ushort predictor = (ushort)(frame[0] | (frame[1] << 8));
        Write(pcm, 0, predictor);
        for (int i = 2, o = 1; i < frame.Length; i++, o++)
        {
            predictor = (ushort)(predictor + DeltaTable[frame[i]]);
            Write(pcm, o * 2, predictor);
        }
        return pcm;
    }

    private static byte[] DecodeStereo(ReadOnlySpan<byte> frame)
    {
        if (frame.Length < 4)
            return [];
        int pairs = (frame.Length - 4) / 2;
        var pcm = new byte[(2 + pairs * 2) * 2];
        ushort l = (ushort)(frame[0] | (frame[1] << 8));
        ushort r = (ushort)(frame[2] | (frame[3] << 8));
        Write(pcm, 0, l);
        Write(pcm, 2, r);
        int src = 4, dst = 4;
        for (int i = 0; i < pairs; i++)
        {
            l = (ushort)(l + DeltaTable[frame[src++]]);
            Write(pcm, dst, l); dst += 2;
            r = (ushort)(r + DeltaTable[frame[src++]]);
            Write(pcm, dst, r); dst += 2;
        }
        return pcm;
    }

    private static void Write(byte[] buf, int offset, ushort sample)
    {
        buf[offset] = (byte)sample;
        buf[offset + 1] = (byte)(sample >> 8);
    }
}
